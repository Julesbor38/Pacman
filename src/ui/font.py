def text_width(text: str, scale: int) -> int:
    """Return the width in pixels of a line of text."""
    return len(text) * CHAR_ADVANCE * scale


def draw_text(
    surface: pygame.Surface,
    x: int,
    y: int,
    text: str,
    color: Color,
    scale: int = 2,
) -> None:
    """Draw text with its top-left corner at (x, y), each dot scale x scale."""
    cursor = x
    for char in text.upper():
        rows = GLYPHS.get(char, GLYPHS[" "])
        for row_index, row in enumerate(rows):
            for col_index, bit in enumerate(row):
                if bit != "1":
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        put_pixel(
                            surface,
                            cursor + col_index * scale + dx,
                            y + row_index * scale + dy,
                            color,
                        )
        cursor += CHAR_ADVANCE * scale
